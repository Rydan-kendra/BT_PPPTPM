public class CDiem {
    private float x;
    private float y;

    public CDiem() {
        x = 0;
        y = 0;
    }

    public CDiem(float x, float y) {
        this.x = x;
        this.y = y;
    }

    public float getX() {
        return x;
    }

    public float getY() {
        return y;
    }
}